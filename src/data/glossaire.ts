function cle(s: string): string {
  return s
    .toLowerCase()
    .replace(/[\u064B-\u0652\u0670\u0640]/g, '')
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/\s+/g, ' ')
    .trim();
}

let index: Map<string, TermeGlossaire> | null = null;

/** مصطلح المسرد المطابق لكلمة مفتاحية من الملخّص (بالتطبيع والمرادفات)، أو undefined. */
export function termeGlossaire(mot: string): TermeGlossaire | undefined {
  if (!index) {
    index = new Map();
    for (const t of GLOSSAIRE) {
      index.set(cle(t.ar), t);
      for (const a of t.alias ?? []) index.set(cle(a), t);
    }
  }
  return index.get(cle(mot));
}

/** بحث في المسرد بالعربية أو الفرنسية (جزئي). */
export function chercherGlossaire(q: string, limite = 30): TermeGlossaire[] {
  const k = cle(q);
  if (k.length < 2) return [];
  return GLOSSAIRE.filter((t) => cle(t.ar).includes(k) || t.fr.toLowerCase().includes(k) || (t.alias ?? []).some((a) => cle(a).includes(k))).slice(0, limite);
}
