/** تعيد كبسولة المُرشد الصوتية الموافقة لوحدة من وحدات البرنامج الإحدى عشرة. */
export function audioPourUnite(uniteId: string): PisteAudioMourchid | undefined {
  return AUDIO_MOURCHID.find((p) => p.unites.includes(uniteId));
}

/** كبسولات المنهجية الثلاث المعروضة في شاشة المُرشد. */
export function audiosMethodo(): PisteAudioMourchid[] {
  return AUDIO_MOURCHID.filter((p) => p.categorie === 'methodo');
}

/** كبسولات المنهجية المرتبطة بفرع محدّد من شجرة المُرشد. */
export function audiosPourBranche(brancheId: string): PisteAudioMourchid[] {
  return AUDIO_MOURCHID.filter((p) => Boolean(p.branchesMourchid?.includes(brancheId)));
}
