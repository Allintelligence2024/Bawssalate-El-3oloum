/** تواتر الأفعال الإجرائية عبر كلّ المواضيع المهيكلة — يُحسب من البيانات لا يُكتب يدويًّا */
export function frequenceVerbes(sujets: SujetOfficiel[] = SUJETS_OFFICIELS): { verbe: VerbeConsigne; n: number }[] {
  const c = new Map<VerbeConsigne, number>();
  for (const s of sujets) for (const e of s.exercices) for (const p of e.parties) for (const q of p.consignes) c.set(q.verbe, (c.get(q.verbe) ?? 0) + 1);
  return [...c.entries()].map(([verbe, n]) => ({ verbe, n })).sort((a, b) => b.n - a.n);
}

/** عدد مرّات استهداف كلّ وحدة (الوحدة الرئيسية للتمرين فقط) */
export function frequenceUnites(sujets: SujetOfficiel[] = SUJETS_OFFICIELS): Record<string, number> {
  const r: Record<string, number> = {};
  for (const s of sujets) for (const e of s.exercices) r[e.unites[0]] = (r[e.unites[0]] ?? 0) + 1;
  return r;
}

