/**
 * اختيار استقصاء الامتحان التجريبي تكيّفيًا (Lot 5C):
 * - يتجنّب تكرار آخر الاستقصاءات المنجَزة في `etat.examens`.
 * - يمنح أولوية للاستقصاءات المرتبطة بوحدات ضعيفة في الامتحانات السابقة أو تحتوي دروسًا هشّة.
 * - حتمي وقابل للاختبار دون عشوائية غير منضبطة.
 */
export function choisirEnqueteExamBlanc(etat: Etat): EnqueteBac {
  const faitsIds = new Set(
    (etat.examens ?? []).map((e) => e.enqueteId).filter((id): id is string => Boolean(id)),
  );
  const nonFaits = ENQUETES_BAC.filter((e) => !faitsIds.has(e.id));
  const candidats = nonFaits.length > 0 ? nonFaits : ENQUETES_BAC;

  const unitesFaiblesRecentes = new Set(
    (etat.examens ?? []).slice(-3).flatMap((e) => e.unitesFaibles.map((n) => `u${n}`)),
  );

  const score = (e: EnqueteBac): number => {
    let s = 0;
    if (unitesFaiblesRecentes.has(e.unitId)) s += 4;
    const u = UNITE_PAR_ID[e.unitId];
    if (u) {
      const aFragile = u.lessonIds.some((lid) => etat.progression[lid]?.fragile);
      const aTerminee = u.lessonIds.some((lid) => etat.progression[lid]?.statut === 'terminee');
      if (aFragile) s += 3;
      if (aTerminee) s += 1;
    }
    return s;
  };

  let meilleur = candidats[0];
  let meilleurScore = score(meilleur);
  for (let i = 1; i < candidats.length; i++) {
    const sc = score(candidats[i]);
    if (sc > meilleurScore) {
      meilleur = candidats[i];
      meilleurScore = sc;
    }
  }
  return meilleur;
}

