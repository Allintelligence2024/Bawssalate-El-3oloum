export type TypeFigure = 'courbe' | 'colonnes' | 'schema';

export interface SerieFigure {
  nom: string;
  /** لون من لوحة التطبيق */
  couleur: 'forest' | 'gold' | 'clay' | 'sage' | 'ink';
  /** نقاط معطاة بالقيم الحقيقية للمحورين */
  points: [number, number][];
  /** خطّ متقطّع = شاهد/مرجع */
  pointille?: boolean;
  /** شكل العلّامة: دائرة، مربّع، مثلّث */
  marque?: 'rond' | 'carre' | 'triangle';
}

export interface Figure {
  /** مفتاح داخلي، يُستعمل في التصحيح */
  cle: string;
  titre: string;
  type: TypeFigure;
  /** ما تقوله الوثيقة، بلغة التلميذ */
  legende: string;
  /** تحرير المحورين — إلزامي للقارئ */
  axeX?: { nom: string; min: number; max: number; pas: number; unite?: string };
  axeY?: { nom: string; min: number; max: number; pas: number; unite?: string };
  series?: SerieFigure[];
  /** للرسوم التفسيرية فقط */
  schema?: string;
}

